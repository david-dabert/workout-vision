// Writes src/lib/counting/spec-profiles.json: for every catalogue exercise with a counted joint (guide-patterns.json) and
// a motion spec with reps (test/real-phone/synth/motions/<key>.json), the spec's signal profile as the spec-guided
// counter reads it (test/real-phone/template/sgc.js specProfile, the spec posed at rest and at its working end through
// fk.js): which of PSC's signals the rep moves, which way (+1 or -1) and by how many noise units (strength; the weight
// is min(strength, W_CAP)), strongest first, cut to the signals the rep signal keeps (MIN_STRENGTH, SHARE). The app's
// body check and its second candidate read this file (src/lib/counting/bodyCheck.js, sgc.js), so the app never poses a
// skeleton. Left out: a spec with no reps and one that alternates sides (alternate true), whose two sides the check
// cannot compare with one joint. mode: 'side' for a one-limb spec (the left side's signals; the right's are their
// mirror), 'mirror' for a spec whose reps alternate as mirror images (lunges), else 'both'. first: the exercise's first
// phase (guide-families.json). Strength to 6 significant digits.
// Run after any change to a motion spec, fk.js or sgc.js: node scripts/make-spec-profiles.mjs
// src/lib/counting/__tests__/bodyCheck.test.ts ("is the generator's output") fails when the committed file differs from
// this script's output.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { specProfile } from '../test/real-phone/template/sgc.js';
import { MIN_STRENGTH, SHARE } from '../src/lib/counting/sgc.js';

const at = p => new URL(p, import.meta.url);
export const OUT = fileURLToPath(at('../src/lib/counting/spec-profiles.json'));

/** The file's text. */
export function makeSpecProfiles() {
  const patterns = JSON.parse(readFileSync(at('../src/lib/counting/guide-patterns.json'), 'utf8'));
  const families = JSON.parse(readFileSync(at('../src/lib/counting/guide-families.json'), 'utf8'));
  const lines = [];
  for (const key of Object.keys(patterns).sort()) {
    const file = at(`../test/real-phone/synth/motions/${key}.json`);
    if (!existsSync(file)) continue;
    const spec = JSON.parse(readFileSync(file, 'utf8'));
    if (spec.noReps || spec.alternate === true) continue;
    const mode = spec.side ? 'side' : spec.alternate === 'mirror' ? 'mirror' : 'both';
    let prof = specProfile(spec, mode === 'side' ? 'left' : mode);
    if (mode === 'side') prof = prof.filter(p => !/R$/.test(p.name));
    const top = prof.length ? prof[0].strength : 0;
    const signals = prof.filter(p => p.strength >= MIN_STRENGTH && p.strength >= SHARE * top)
      .map(p => [p.name, Math.sign(p.delta), Number(p.strength.toPrecision(6))]);
    if (!signals.length) continue;
    const first = families[spec.key]?.first ?? 'concentric';
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify({ mode, first, signals })}`);
  }
  const note = 'Generated by scripts/make-spec-profiles.mjs from the motion specs through fk.js (sgc.js specProfile); do not edit. signals: [name, direction, strength in noise units], strongest first.';
  return `{\n "note": ${JSON.stringify(note)},\n "profiles": {\n${lines.join(',\n')}\n }\n}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = makeSpecProfiles();
  writeFileSync(OUT, text);
  console.log(`spec-profiles.json: ${Object.keys(JSON.parse(text).profiles).length} exercises, ${text.length} bytes`);
}
